"""Muninn SSRF evidence analyzer (offline, standard-library only).

This module NEVER sends network requests. Observations and OAST events must
come from an explicitly authorized test harness. Results are review signals,
not automatic declarations of exploitable SSRF.
"""
from __future__ import annotations

from dataclasses import dataclass, field, asdict
from collections import defaultdict
from hashlib import sha256
from ipaddress import ip_address
from statistics import median
from typing import Callable, Iterable, Mapping, Optional
from urllib.parse import urlsplit, parse_qsl, unquote
import json
import re

URL_KEYS = frozenset({"url", "uri", "link", "target", "destination", "dest", "redirect", "callback", "webhook", "feed", "image_url", "avatar_url", "proxy", "endpoint", "fetch", "resource", "src"})
CLOUD_HOSTS = frozenset({"169.254.169.254", "metadata.google.internal", "metadata.azure.internal"})


def _digest(value: str) -> str:
    return sha256(value.encode('utf-8', errors='replace')).hexdigest()[:20]


def _hostname(url: str) -> Optional[str]:
    try:
        p = urlsplit(url)
        if p.scheme.lower() not in {"http", "https"} or not p.netloc:
            return None
        return p.hostname.lower().rstrip('.') if p.hostname else None
    except ValueError:
        return None


def _url_parts(value: str):
    try:
        return urlsplit(value)
    except ValueError:
        return None


def _decode(value: str, rounds: int = 3) -> str:
    for _ in range(rounds):
        updated = unquote(value)
        if updated == value:
            break
        value = updated
    return value


def _ip_class(host: str) -> Optional[str]:
    """Classify literal IPs without resolving hostnames or contacting DNS."""
    host = host.strip('[]')
    try:
        ip = ip_address(host)
    except ValueError:
        return None
    if ip.is_loopback:
        return 'loopback'
    if ip.is_link_local:
        return 'link_local'
    if ip.is_private:
        return 'private'
    if ip.is_multicast:
        return 'multicast'
    if ip.is_reserved or ip.is_unspecified:
        return 'reserved'
    return 'public'


def classify_destination(value: str) -> tuple[str, ...]:
    """Conservative static URL indicators; never performs DNS resolution."""
    value = _decode(value.strip())
    flags = set()
    p = _url_parts(value)
    if p is None:
        return ('malformed_url',)
    scheme = p.scheme.lower()
    if scheme and scheme not in {'http', 'https'}:
        flags.add('non_http_scheme')
    if value.startswith('//'):
        flags.add('scheme_relative')
    if '\\' in value:
        flags.add('backslash')
    if p.username is not None or p.password is not None:
        flags.add('userinfo')
    try:
        host = p.hostname.lower().rstrip('.') if p.hostname else ''
        _ = p.port
    except ValueError:
        flags.add('malformed_url')
        host = ''
    if host in CLOUD_HOSTS:
        flags.add('metadata_destination')
    if host in {'localhost', 'localhost.localdomain'} or host.endswith('.localhost'):
        flags.add('loopback_hostname')
    if host.endswith(('.internal', '.local', '.test')) and host not in {'metadata.google.internal', 'metadata.azure.internal'}:
        flags.add('internal_hostname_hint')
    ip_kind = _ip_class(host)
    if ip_kind and ip_kind != 'public':
        flags.add('ip_' + ip_kind)
    if host and not ip_kind and re.fullmatch(r'0[xX][0-9a-fA-F]+|0[0-9]+|\d+', host):
        flags.add('noncanonical_numeric_host')
    if not scheme and not value.startswith('//'):
        flags.add('relative_or_unqualified')
    return tuple(sorted(flags))


@dataclass(frozen=True)
class SSRFObservation:
    url: str
    parameter: str
    candidate_url: str
    scenario: str = 'default'
    method: str = 'GET'
    status: Optional[int] = None
    baseline_status: Optional[int] = None
    elapsed_ms: Optional[float] = None
    baseline_elapsed_ms: Optional[float] = None
    # A nonce generated by the caller for a single authorized test.
    correlation_id: str = ''
    # Trusted independent fixture: response contained a unique benign marker.
    response_marker_verified: bool = False
    # Explicitly authorized and independently verified boundary violation.
    unauthorized_boundary_verified: bool = False


@dataclass(frozen=True)
class OASTEvent:
    correlation_id: str
    # DNS-only events are weak; HTTP events establish a request reached the listener.
    protocol: str
    # Only set true if the collector authenticated the event and attributed it
    # to the test (not a browser, link scanner, or unrelated service).
    trusted: bool = False
    source_attributed: bool = False


@dataclass(frozen=True)
class SSRFPolicy:
    max_observations: int = 10000
    max_events: int = 20000
    max_findings: int = 5000
    max_field_chars: int = 8192
    timing_threshold_ms: float = 1000.0
    timing_ratio: float = 2.5
    min_timing_samples: int = 3

    def __post_init__(self):
        if min(self.max_observations, self.max_events, self.max_findings, self.max_field_chars, self.min_timing_samples) < 1:
            raise ValueError('limits must be positive')
        if self.timing_threshold_ms <= 0 or self.timing_ratio <= 1:
            raise ValueError('invalid timing thresholds')


@dataclass(frozen=True)
class SSRFFinding:
    code: str
    confidence: str
    severity: str
    endpoint_hash: str
    parameter_hash: str
    scenario_hash: str
    evidence: Mapping[str, object] = field(default_factory=dict)


@dataclass(frozen=True)
class SSRFReport:
    findings: tuple[SSRFFinding, ...]
    analyzed: int
    skipped_out_of_scope: int
    skipped_invalid: int
    truncated: bool

    def to_json(self) -> str:
        return json.dumps(asdict(self), sort_keys=True, separators=(',', ':'))


class SSRFAuditor:
    def __init__(self, policy: Optional[SSRFPolicy] = None):
        self.policy = policy or SSRFPolicy()

    def analyze(self, observations: Iterable[SSRFObservation], *, scope_check: Callable[[str], bool],
                oast_events: Iterable[OASTEvent] = ()) -> SSRFReport:
        if not callable(scope_check):
            raise TypeError('scope_check must be callable')
        p = self.policy
        findings: list[SSRFFinding] = []
        seen: set[tuple] = set()
        event_map: dict[str, list[OASTEvent]] = defaultdict(list)
        truncated = False
        for idx, event in enumerate(oast_events):
            if idx >= p.max_events:
                truncated = True
                break
            if isinstance(event, OASTEvent) and event.correlation_id and len(event.correlation_id) <= p.max_field_chars:
                event_map[event.correlation_id].append(event)

        analyzed = out_scope = invalid = 0
        timing_groups: dict[tuple[str, str, str], list[tuple[float, float]]] = defaultdict(list)

        def add(code: str, confidence: str, severity: str, obs: SSRFObservation, evidence: Mapping[str, object]):
            nonlocal truncated
            key = (code, obs.url, obs.parameter, obs.scenario)
            if key in seen:
                return
            if len(findings) >= p.max_findings:
                truncated = True
                return
            seen.add(key)
            findings.append(SSRFFinding(code, confidence, severity, _digest(obs.url),
                                        _digest(obs.parameter), _digest(obs.scenario), dict(evidence)))

        for idx, obs in enumerate(observations):
            if idx >= p.max_observations:
                truncated = True
                break
            if not isinstance(obs, SSRFObservation) or any(len(x) > p.max_field_chars for x in
                    (obs.url, obs.parameter, obs.candidate_url, obs.scenario, obs.correlation_id)):
                invalid += 1
                continue
            if _hostname(obs.url) is None:
                invalid += 1
                continue
            # Fail closed: scope checker exceptions propagate; no results for that target.
            if not scope_check(obs.url):
                out_scope += 1
                continue
            analyzed += 1
            flags = classify_destination(obs.candidate_url)
            param = obs.parameter.casefold().strip()
            if param in URL_KEYS or param.endswith(('_url', '_uri', '_host')):
                add('url_fetch_input', 'low', 'informational', obs, {'parameter_kind': 'url_like'})
            risky = tuple(x for x in flags if x in {
                'metadata_destination', 'ip_loopback', 'ip_link_local', 'ip_private',
                'loopback_hostname', 'internal_hostname_hint', 'noncanonical_numeric_host',
                'non_http_scheme', 'userinfo', 'backslash', 'scheme_relative'})
            if risky:
                add('destination_review', 'low', 'low', obs, {'indicators': risky})
            if obs.status is not None and obs.baseline_status is not None and obs.status != obs.baseline_status:
                add('response_status_difference', 'low', 'informational', obs,
                    {'status': obs.status, 'baseline_status': obs.baseline_status})
            if obs.elapsed_ms is not None and obs.baseline_elapsed_ms is not None:
                if 0 <= obs.elapsed_ms <= 600000 and 0 <= obs.baseline_elapsed_ms <= 600000:
                    timing_groups[(obs.url, obs.parameter, obs.scenario)].append((obs.elapsed_ms, obs.baseline_elapsed_ms))
            if obs.response_marker_verified:
                add('verified_response_marker', 'medium', 'medium', obs,
                    {'proof': 'trusted_unique_benign_marker'})
            if obs.unauthorized_boundary_verified:
                add('verified_boundary_violation', 'high', 'high', obs,
                    {'proof': 'trusted_independent_boundary_verification'})
            if obs.correlation_id:
                events = [e for e in event_map.get(obs.correlation_id, ()) if e.trusted and e.source_attributed]
                if any(e.protocol.lower() in {'http', 'https'} for e in events):
                    add('oast_http_callback', 'high', 'medium', obs, {'proof': 'trusted_attributed_http_callback'})
                elif any(e.protocol.lower() == 'dns' for e in events):
                    add('oast_dns_callback', 'medium', 'low', obs, {'proof': 'trusted_attributed_dns_callback'})

        for key, samples in sorted(timing_groups.items()):
            if len(samples) < p.min_timing_samples:
                continue
            candidate = [x[0] for x in samples]
            baseline = [x[1] for x in samples]
            delta = median(candidate) - median(baseline)
            if delta >= p.timing_threshold_ms and median(candidate) >= p.timing_ratio * max(1.0, median(baseline)):
                # Report only a weak timing signal: independent OAST is needed for confirmation.
                representative = SSRFObservation(key[0], key[1], '', scenario=key[2])
                add('timing_difference', 'low', 'informational', representative,
                    {'sample_count': len(samples), 'median_delta_ms': round(delta, 2)})

        return SSRFReport(tuple(sorted(findings, key=lambda f: (f.endpoint_hash, f.parameter_hash, f.scenario_hash, f.code))),
                          analyzed, out_scope, invalid, truncated)


__all__ = ['SSRFObservation', 'OASTEvent', 'SSRFPolicy', 'SSRFFinding', 'SSRFReport',
           'SSRFAuditor', 'classify_destination']
